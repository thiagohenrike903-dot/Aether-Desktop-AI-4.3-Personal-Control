    "USER",
    "USERNAME",
    "USERPROFILE",
    "LOGNAME",
    "APPDATA",
    "LOCALAPPDATA",
    "PROGRAMDATA",
    "PROGRAMFILES",
    "PROGRAMFILES(X86)",
    "PROGRAMW6432",
    "TEMP",
    "TMP",
    "TMPDIR",
    # Locale/terminal/display integration.
    "LANG",
    "LANGUAGE",
    "TERM",
    "COLORTERM",
    "DISPLAY",
    "WAYLAND_DISPLAY",
    "DBUS_SESSION_BUS_ADDRESS",
